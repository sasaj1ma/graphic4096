export const GLYPH_W = 5;
export const GLYPH_H = 7;

// 文字 1つの row 行目を5bitで返す。知らない文字は空白として扱う。
export function glyphRow(character, row) {
  const rows = GLYPHS[character] ?? GLYPHS[' '];
  return rows[row] ?? 0;
}

// 文字列を1行だけ流し読みする。text 空間の座標 (sx, sy) が字画の上なら true。
// sx は左右に無限に伸びる。折り返しはここで面倒を見るので、呼ぶ側は座標を渡すだけでよい。
export function textBit(text, sx, sy, scale = 1, gap = 1) {
  const cell = GLYPH_W * scale + gap;
  const span = text.length * cell;
  if (span <= 0) return false;

  const wrapped = ((sx % span) + span) % span;
  const index = Math.floor(wrapped / cell);
  const inner = wrapped - index * cell;
  if (inner >= GLYPH_W * scale) return false; // 字間

  const row = Math.floor(sy / scale);
  if (row < 0 || row >= GLYPH_H) return false;
  const column = Math.floor(inner / scale);
  return ((glyphRow(text[index], row) >> (GLYPH_W - 1 - column)) & 1) === 1;
}
