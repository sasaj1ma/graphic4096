// 2本目のスケッチ。
// x方向ごとに流れる光のラインを描き、雨やデジタルの滝のような表現を作る。
export function draw(api) {

  // 現在の時間（秒）
  // この値が増え続けることで光が下へ流れる。
  const t = api.time();

  // -----------------------------
  // 背景を塗る
  // -----------------------------
  //
  // 毎フレーム画面全体を濃い青で塗りつぶす。
  // clear() を呼ばないと前フレームが残り、
  // 残像のような表現になる。
  api.clear(api.rgb(1, 4, 13));

  // -----------------------------
  // 各列(x方向)を処理する
  // -----------------------------
  //
  // このスケッチでは1列につき1本の光だけを描く。
  for (let x = 0; x < api.width; x += 1) {

    // -----------------------------
    // 列ごとの開始位置を決める
    // -----------------------------
    //
    // noise() を使うことで、
    // 隣り合う列が少しずつ違う位置になる。
    //
    // x * 0.19
    //   → 横方向の変化の細かさ
    //
    // 4
    //   → ノイズ空間の固定値
    //
    // noise() は0〜1を返すので、
    // 高さを掛けて画面内の位置に変換する。
    const offset =
      api.noise(x * 0.19, 4) * api.height;

    // -----------------------------
    // 光の位置を計算する
    // -----------------------------
    //
    // t * 18
    //   → 毎秒18ピクセルの速度で下へ移動
    //
    // offset
    //   → 列ごとに開始位置をずらす
    //
    // % api.height
    //   → 一番下まで行くと上へ戻る
    const y = Math.floor(
      (t * 18 + offset) % api.height
    );

    // -----------------------------
    // 明るい先頭を描く
    // -----------------------------
    //
    // シアン色の光。
    api.pixel(
      x,
      y,
      api.rgb(110, 230, 255)
    );

    // -----------------------------
    // その下に少し暗い色を描く
    // -----------------------------
    //
    // 光に厚みを持たせるため、
    // 1ピクセル下へ青色を描く。
    //
    // % api.height により、
    // 最下段でも上へつながる。
    api.pixel(
      x,
      (y + 1) % api.height,
      api.rgb(23, 113, 178)
    );
  }
}
