// 毎フレーム呼ばれる描画関数
export function draw(api) {
  // 現在の時間（秒）
  // この値が増え続けることでアニメーションになる
  const t = api.time();

  // 画面全体（LEDマトリクス）を1ピクセルずつ処理する
  for (let y = 0; y < api.height; y += 1) {
    for (let x = 0; x < api.width; x += 1) {

      // -----------------------------
      // 波（Wave）を作る
      // -----------------------------
      // x方向とy方向のサイン波を重ね合わせる。
      //
      // x * 0.17
      //   → 波長（数値を小さくすると波が大きくなる）
      //
      // + t
      //   → 時間によって右へ流れる
      //
      // y * 0.14
      //   → 縦方向の波
      //
      // - t * 1.3
      //   → 少し速い速度で逆方向へ流れる
      //
      // この2つを足すことで、水面のような複雑な干渉模様になる。
      const wave =
        Math.sin(x * 0.17 + t) +
        Math.sin(y * 0.14 - t * 1.3);

      // -----------------------------
      // ノイズ（Cloud）を作る
      // -----------------------------
      // Perlin Noise のような滑らかな乱数。
      //
      // x,y が近い場所は似た値になるため、
      // ランダムではなく雲や煙のような模様になる。
      //
      // t を3番目の引数に入れることで、
      // ノイズ空間の中をゆっくり移動し、
      // 雲が漂うようなアニメーションになる。
      const cloud = api.noise(
        x * 0.09,
        y * 0.09,
        t * 0.25
      );

      // -----------------------------
      // 波とノイズを合成する
      // -----------------------------
      //
      // 0.5 を基準値とし、
      //
      // wave * 0.15
      //   → 波の影響（少し弱め）
      //
      // (cloud - 0.5) * 0.9
      //   → ノイズを中心0にして強めに効かせる
      //
      // 最終的な明るさ(value)を作る。
      let value =
        0.5 +
        wave * 0.15 +
        (cloud - 0.5) * 0.9;

      // 値が0未満や1を超えると扱いにくいため、
      // 0〜1の範囲に丸める（Clamp）
      value = Math.max(0, Math.min(1, value));

      // -----------------------------
      // 描画
      // -----------------------------
      //
      // value(0〜1)に応じて
      // neonパレットから色を取得して描画する。
      //
      // value = 0   → 暗い色
      // value = 1   → 明るい色
      api.pixel(x, y, api.palette('neon', value));
    }
  }
}
